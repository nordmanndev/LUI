#!/usr/bin/env bash
#
# fetch-wordlist.sh — download the German word list for the normalisation
# parity test (LUI-Spezifikation §19).
#
# The list is the "Deutsche Wörterliste" with 685,829 entries — the number the
# specification names. It is published under CC0 1.0 (public domain
# dedication), so it may be checked in, redistributed and used without
# conditions.
#
#   Original list:  https://github.com/enz/german-wordlist  (CC0-1.0)
#   Mirror of the University of Leipzig's list, which is the same data. The
#   Leipzig download itself (https://www.wortschatz.uni-leipzig.de/download/Deminck)
#   sits behind an anti-bot wall and is not reachable from a script — the
#   mirror is the reason this script works at all.
#
# The full list is NOT checked in: 5.5 MB of data that nobody reviews. The
# deterministic sample that the CI runs on every pull request lives in
# tests/Nordmann.LUI.TestData/wordlist/ and is regenerated by
# tools/make-curated-corpus.sh.
#
# Usage:
#   tools/fetch-wordlist.sh                 # → artifacts/wordlist/german-words.txt
#   tools/fetch-wordlist.sh <target-path>
#
set -euo pipefail

readonly SOURCE_URL="https://raw.githubusercontent.com/enz/german-wordlist/master/words"
readonly ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly TARGET="${1:-${ROOT}/artifacts/wordlist/german-words.txt}"
readonly EXPECTED_LINES=685829

if ! command -v curl >/dev/null 2>&1; then
  echo "fetch-wordlist: curl is required" >&2
  exit 1
fi

mkdir -p "$(dirname "${TARGET}")"

echo "fetch-wordlist: downloading ${SOURCE_URL}"
if ! curl -fsSL --retry 3 --retry-delay 2 --max-time 300 "${SOURCE_URL}" -o "${TARGET}.tmp"; then
  echo "fetch-wordlist: download failed" >&2
  rm -f "${TARGET}.tmp"
  exit 1
fi

# The list is UTF-8 with Unix line endings; strip a possible BOM and a
# trailing carriage return so the file is byte-stable across platforms.
sed -e 's/\r$//' -e '1s/^\xEF\xBB\xBF//' "${TARGET}.tmp" > "${TARGET}"
rm -f "${TARGET}.tmp"

lines="$(wc -l < "${TARGET}" | tr -d ' ')"
if [ "${lines}" != "${EXPECTED_LINES}" ]; then
  echo "fetch-wordlist: expected ${EXPECTED_LINES} words, got ${lines}" >&2
  echo "fetch-wordlist: the source changed — check it before trusting the parity run" >&2
  exit 1
fi

echo "fetch-wordlist: ${lines} words → ${TARGET}"
echo "fetch-wordlist: run the parity test with LUI_WORDLIST=${TARGET}"
