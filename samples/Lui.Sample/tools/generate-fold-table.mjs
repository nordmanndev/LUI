// Generates wwwroot/js/suggest/fold-table.js from the table LUI measured from SQLite's trigram tokenizer:
//   node tools/generate-fold-table.mjs
// The client-test `fold-table.test.js` fails when the module and the table disagree, and says to run this.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '../../../src/Nordmann.LUI/Normalization/tokenizer-fold.txt');
const target = path.resolve(here, '../wwwroot/js/suggest/fold-table.js');

const entries = fs.readFileSync(source, 'utf8')
    .split('\n')
    .filter(line => line && !line.startsWith('#'));

fs.writeFileSync(target, `/*
 * GENERATED by tools/generate-fold-table.mjs from src/Nordmann.LUI/Normalization/tokenizer-fold.txt — do not edit by hand.
 *
 * What the tokenizer of the search index (FTS5 trigram, remove_diacritics 1) makes of each code point of the Basic
 * Multilingual Plane: "from to" in hex, one character each; "-" means the character is dropped (the combining marks).
 * A code point that is not listed is passed through unchanged — đ, ł, ø, ħ and ı among them. The table is *measured*, not
 * derived from Unicode, which is why it is the one thing to copy (docs/normalization.md, section 2).
 */
const LINES = \`
${entries.join('\n')}
\`;

/** @type {Map<number, string>} code point → what the tokenizer makes of it ('' = dropped) */
export const TOKENIZER_FOLD = new Map(
    LINES.trim().split('\\n').map(line => {
        const [from, to] = line.split(' ');
        return [Number.parseInt(from, 16), to === '-' ? '' : String.fromCodePoint(Number.parseInt(to, 16))];
    }));
`);
console.log(`${entries.length} entries written to ${path.relative(process.cwd(), target)}`);
