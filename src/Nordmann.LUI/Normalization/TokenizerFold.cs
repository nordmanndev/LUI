using System.Globalization;

namespace Nordmann.LUI.Normalization;

/// <summary>
/// The per-character folding that FTS5's trigram tokenizer applies: the case
/// fold and the removal of the diacritics.
/// <para>
/// The table is <b>measured</b>, not derived from the Unicode standard: SQLite
/// folds text with its own tables, and those tables are not the ones .NET
/// ships. A C# implementation that used <c>ToLowerInvariant</c> would fold
/// 696 characters differently from the index — and every one of those is a
/// text the library would silently fail to find.
/// </para>
/// <para>
/// The table is generated by <c>tools/FoldTableGenerator</c> and verified
/// against the live tokenizer by the parity test on every build.
/// </para>
/// </summary>
internal static class TokenizerFold
{
    /// <summary>The marker for a character the tokenizer drops entirely.</summary>
    internal const char Removed = '\0';

    private const string ResourceName = "Nordmann.LUI.tokenizer-fold.txt";

    private static readonly char[] Table = Build();

    /// <summary>
    /// The character the tokenizer makes of <paramref name="value"/> — or
    /// <see cref="Removed"/> when the tokenizer drops it.
    /// </summary>
    internal static char Fold(char value) => Table[value];

    /// <summary>
    /// A stable identity of the table: a hash of its entries, not of the file,
    /// so that line endings do not change it. It is stored in <c>lui_meta</c>;
    /// an index stored with another table has to be built again.
    /// </summary>
    internal static string Version { get; } = ComputeVersion();

    /// <summary>The entries of the table, as listed in the resource.</summary>
    internal static IReadOnlyList<(int From, char To)> Listed { get; } = [.. Entries()];

    private static string ComputeVersion()
    {
        var text = string.Join(
            '\n',
            Entries().Select(entry => string.Create(CultureInfo.InvariantCulture, $"{entry.From:X4}:{(int)entry.To:X4}")));

        var hash = System.Security.Cryptography.SHA256.HashData(System.Text.Encoding.UTF8.GetBytes(text));
        return Convert.ToHexString(hash.AsSpan(0, 8)).ToLowerInvariant();
    }

    private static char[] Build()
    {
        var table = new char[0x10000];
        for (var i = 0; i < table.Length; i++)
        {
            table[i] = (char)i;
        }

        foreach (var (from, to) in Entries())
        {
            table[from] = to;
        }

        return table;
    }

    private static IEnumerable<(int From, char To)> Entries()
    {
        using var stream = typeof(TokenizerFold).Assembly.GetManifestResourceStream(ResourceName)
            ?? throw new InvalidOperationException(
                $"The embedded resource '{ResourceName}' is missing from the assembly.");

        using var reader = new StreamReader(stream);

        while (reader.ReadLine() is { } line)
        {
            if (line.Length == 0 || line[0] == '#')
            {
                continue;
            }

            var parts = line.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            var from = int.Parse(parts[0], NumberStyles.HexNumber, CultureInfo.InvariantCulture);

            if (parts.Length < 2 || string.Equals(parts[1], "-", StringComparison.Ordinal))
            {
                yield return (from, Removed);
                continue;
            }

            var to = (char)int.Parse(parts[1], NumberStyles.HexNumber, CultureInfo.InvariantCulture);
            yield return (from, to);
        }
    }
}
